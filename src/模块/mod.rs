//! 壳语言的各层实现（目录与文件名一律用中文）。
//!
//! - [`词法`]：把输入行解析成作业（管道 / 重定向 / 后台 / 引号 / 变量）；
//! - [`释义`]：把作业翻译成可直接执行的「管道片段」，并标出内置命令；
//! - [`执行`]：分叉进程 + 管道 + 重定向 + 等待进程的整套编排；
//! - [`内置`]：`cd`、`export`、`exit` 等 shell 自身命令；
//! - [`壳`]：把上面几层串起来，并提供提示符与变量表；
//! - [`系统调用`]：手写的极简 C 库绑定（不依赖任何 crate）。

// 所有文件都通过 `#[path]` 显式指定：Rust 不允许用非 ASCII 标识符名直接推断文件路径，
// 因此「目录 / 文件名一律用中文」需要在这里手动接线。
#[path = "壳.rs"]
pub mod 壳;
#[path = "内置.rs"]
pub mod 内置;
#[path = "执行.rs"]
pub mod 执行;
#[path = "释义.rs"]
pub mod 释义;
#[path = "词法.rs"]
pub mod 词法;
#[path = "系统调用.rs"]
pub mod 系统调用;
