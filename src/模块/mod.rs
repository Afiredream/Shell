//! 壳语言的各层实现。
//!
//! - [`词法`]：把输入行解析成作业（管道 / 重定向 / 后台 / 引号 / 变量）；
//! - [`释义`]：把作业翻译成直接的「命令计划」，内置命令单独标记；
//! - [`执行`]：`fork` + `pipe` + `execvp` 的进程编排；
//! - [`内置`]：`cd`、`export`、`exit` 等 shell 自身命令；
//! - [`shell`]：把上面几层串起来，并提供提示符与环境变量表；
//! - [`系统调用`]：手写的极简 libc 绑定（不依赖任何 crate）。

